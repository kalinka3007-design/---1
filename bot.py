# ОБРАБОТЧИК КОМАНДЫ /reply (для администратора)
# ==============================================

async def reply_to_user(update: Update, context: ContextTypes.DEFAULT_TYPE):
    if not ADMIN_CHAT_ID:
        await update.message.reply_text("Администратор не настроен.")
        return

    if str(update.effective_user.id) != ADMIN_CHAT_ID:
        await update.message.reply_text("У вас нет прав для использования этой команды.")
        return

    args = context.args
    if len(args) < 2:
        await update.message.reply_text("Использование: /reply [user_id] [текст]")
        return

    try:
        user_id = int(args[0])
        reply_text = " ".join(args[1:])
        await context.bot.send_message(chat_id=user_id, text=f"Администратор: {reply_text}")
        await update.message.reply_text(f"✅ Сообщение отправлено пользователю {user_id}.")
    except Exception as e:
        await update.message.reply_text(f"❌ Ошибка: {e}")

# ==============================================
# ОБРАБОТЧИК СООБЩЕНИЙ
# ==============================================

async def handle_message(update: Update, context: ContextTypes.DEFAULT_TYPE):
    user_text = update.message.text
    user_id = update.effective_user.id

    if 'greeted' not in context.user_data:
        context.user_data['greeted'] = False

    if user_text == "/start":
        context.user_data['greeted'] = False
        await update.message.reply_text(
            "Здравствуйте! Я виртуальный помощник студии MintGlow. 😊\n\n"
            "Чем могу помочь? Расскажите, какая процедура вас интересует, и я дам максимально подробную информацию.\n\n"
            "Если вам нужна помощь с записью или вы хотите связаться с администратором, просто напишите «Администратор» или «Хочу записаться»."
        )
        context.user_data['greeted'] = True
        return

    notified = await notify_admin_if_needed(update, context)
    if notified:
        await update.message.reply_text(
            "Я передал ваш запрос администратору. Он свяжется с вами в ближайшее время. 😊"
        )
        return

    try:
        token = get_gigachat_token()
        first_contact = not context.user_data['greeted']
        answer = ask_gigachat(user_text, token, first_contact)
        context.user_data['greeted'] = True

        if len(answer) > 4096:
            for part in split_message(answer):
                await update.message.reply_text(part)
        else:
            await update.message.reply_text(answer)
    except Exception as e:
        if ADMIN_CHAT_ID:
            await context.bot.send_message(
                chat_id=ADMIN_CHAT_ID,
                text=f"⚠️ Ошибка бота для пользователя {user_id}: {str(e)}\nТекст: {user_text}"
            )
        await update.message.reply_text(
            "❌ Произошла техническая ошибка. Я уже уведомил администратора. Пожалуйста, повторите запрос позже или свяжитесь с нами по номеру +7 916 758 51 41 (Telegram / WhatsApp / МАХ)."
        )

